import type { Engine, SolveContext } from "../types.js";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { commandExists } from "../shared.js";
import path from "node:path";

const execFileAsync = promisify(execFile);

function buildCodexPrompt(context: SolveContext) {
    const workerTask = context.workerTask ?? null;
    return [
        "Return only the shell command.",
        "Do not include markdown fences or explanation.",
        "Do not execute anything yourself.",
        "Prefer a shell-gei style one-liner.",
        "Favor stdin/stdout flow with standard Unix tools.",
        workerTask?.strategyProfile?.rubricFocus?.length
            ? `Shellgei rubric focus: ${workerTask.strategyProfile.rubricFocus.join(", ")}`
            : "",
        workerTask?.assignedVariant?.label ? `Assigned variant: ${workerTask.assignedVariant.label}` : "",
        workerTask?.assignedVariant?.approach
            ? `Variant approach: ${workerTask.assignedVariant.approach}`
            : "",
        workerTask?.assignedVariant?.toolBias?.length
            ? `Preferred tool bias: ${workerTask.assignedVariant.toolBias.join(", ")}`
            : "",
        workerTask?.assignedVariant?.intent
            ? `Variant intent: ${workerTask.assignedVariant.intent}`
            : "",
        workerTask?.assignedVariant?.constraints?.length
            ? `Variant constraints: ${workerTask.assignedVariant.constraints.join(", ")}`
            : "",
        workerTask?.assignedVariant?.avoid?.length
            ? `Avoid while exploring: ${workerTask.assignedVariant.avoid.join(", ")}`
            : "",
        workerTask?.assignedVariant?.explorationHint
            ? `Exploration hint: ${workerTask.assignedVariant.explorationHint}`
            : "",
        workerTask?.assignedVariant?.toolSuggestions?.length
            ? `Variant tool suggestions: ${JSON.stringify(workerTask.assignedVariant.toolSuggestions)}`
            : "",
        workerTask?.assignedVariant
            ? "Use assigned variant as a soft exploration axis, not a rigid first step."
            : "",
        workerTask?.assignedVariant?.toolSuggestions?.length
            ? "Use suggestedTools as optional starting points, but choose any safer or better tools if needed."
            : "",
        "Problem:",
        context.problem,
        context.attempts.length > 0 ? `Previous attempts: ${JSON.stringify(context.attempts)}` : ""
    ]
        .filter(Boolean)
        .join("\n");
}

export class CodexCliEngine implements Extract<Engine, { capabilities?: { toolCalling?: false } }> {
    command: string;
    args: string[];
    name = "codex-cli";
    capabilities = Object.freeze({ toolCalling: false });
    constructor(options: { command?: string; args?: string[] } = {}) {
        this.command = options.command ?? "codex";
        this.args = options.args ?? ["exec", "--json"];
    }
    async generateCommand(context: SolveContext) {
        if (!(await commandExists(this.command))) {
            throw new Error(`The '${this.command}' command is not installed or not in PATH.`);
        }
        const prompt = buildCodexPrompt(context);
        const { stdout } = await execFileAsync(this.command, [...this.args, prompt], {
            cwd: context.workdir,
            env: process.env
        });
        const command = String(stdout ?? "").trim();
        if (!command) {
            throw new Error("The Codex CLI engine returned an empty command.");
        }
        return {
            command,
            explanation: "Generated by Codex CLI."
        };
    }
}

function buildCursorPrompt(context: SolveContext) {
    return [
        "Return only a shell command.",
        "Do not include markdown fences or explanation.",
        "Do not execute anything yourself.",
        "Problem:",
        context.problem,
        context.attempts.length > 0 ? `Previous attempts: ${JSON.stringify(context.attempts)}` : ""
    ]
        .filter(Boolean)
        .join("\n");
}

export class CursorCliEngine implements Extract<Engine, { capabilities?: { toolCalling?: false } }> {
    name = "cursor";
    capabilities = Object.freeze({ toolCalling: false });
    async generateCommand(context: SolveContext) {
        const exists = await commandExists("cursor");
        if (!exists) {
            throw new Error("The 'cursor' CLI was not found in PATH. Install it or use --engine mock.");
        }
        const prompt = buildCursorPrompt(context);
        const result = await execFileAsync("cursor", ["agent", prompt], {
            cwd: context.workdir,
            env: {
                PATH: process.env.PATH ?? "",
                HOME: process.env.HOME ?? ""
            },
            timeout: 15000
        });
        const command = result.stdout.trim();
        if (!command) {
            throw new Error("The 'cursor' CLI returned an empty command.");
        }
        return {
            command,
            explanation: "Generated by Cursor CLI."
        };
    }
}

export class MockEngine implements Extract<Engine, { capabilities?: { toolCalling?: false } }> {
    name = "mock";
    capabilities = Object.freeze({ toolCalling: false });
    async generateCommand(context: SolveContext) {
        const lowerProblem = context.problem.toLowerCase();
        const failedBefore = context.attempts.length > 0;
        const samplePath = path.join(context.workdir, "sample.csv");
        if (lowerProblem.includes("3列目") ||
            lowerProblem.includes("third column") ||
            lowerProblem.includes("sum-third-column")) {
            return {
                command: failedBefore
                    ? `awk -F, '{s+=$3} END{print s}' "${samplePath}"`
                    : "awk -F, '{s+=$3} END{print s}' sample.csv",
                explanation: "CSVをカンマ区切りで読み込み、3列目を合計して最後に表示します。"
            };
        }
        return {
            command: "printf 'mock-engine could not infer a better command\\n'",
            explanation: "MVPのmockEngineは既知の例題を優先して処理します。"
        };
    }
}
